#include <stdio.h>

int main() {

    // variable = A reusable container for storing data
    //            Behaves as if it were the vale it contains
    char grade = 'A'; // char = single character/letter/number, stored in single quotes
    char symbol = '@';
    char currancy = '$';
    printf("the currency is american %c \n", currancy); // %c stands for character
    printf("your favorite symbol is %c \n", symbol); // %c stands for character
    printf("your grade is %c \n", grade); // %c stands for character
    return 0;
}
